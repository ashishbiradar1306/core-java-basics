// Finding an first element of an given array

package arrays;

public class FindFirstElement {
    public static void main(String[] args) {
        int[] arr2 = {10, 50, 20, 80, 60};
        for (int i = 0; i < arr2.length; i++) {
            System.out.println(arr2[i]);
            break;
        }
    }
}
