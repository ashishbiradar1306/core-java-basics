package strings;

// Write a Java program to print the first character and the last character of a String using charAt()
public class AccessFirstAndLastCharacter {
    public static void main(String[] args) {
        String str = "Java Programming";
        System.out.println("First index character :" + str.charAt(0));
        System.out.print("Last index character :" + str.charAt(15));
    }
}
