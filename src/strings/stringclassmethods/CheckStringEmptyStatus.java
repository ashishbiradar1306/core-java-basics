package strings.stringclassmethods;

// Write a Java program that checks whether a String is empty or not using isEmpty()

public class CheckStringEmptyStatus {
    public static void main(String[]args){
        String str = "Java";

        if(str.isEmpty()){
            System.out.println("String is empty");
        }else{
            System.out.println("String is not empty");
        }
    }
}
