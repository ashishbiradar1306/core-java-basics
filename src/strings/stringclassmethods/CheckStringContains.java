package strings.stringclassmethods;

// Write a Java program to check whether the given String contains "Java" using the contains() method.

public class CheckStringContains {
    public static void main(String[] args) {

        String str = "I am learning Java Programming";
        System.out.println("Contains Java: " + str.contains("Java"));
        System.out.println("Contains Programming: " + str.contains("Programming"));
    }
}
